#operadores matematicos(aritmeticos)
a=10
b=2.5
#1. suma(+)
print("El resultado de la suma es:",a+b)
#2. resta(-)
print("El resultado de la resta es:",a-b)
#3. multiplicacion(*)
print("El resultado de la multiplicacion es:",a*b)
#4. divicion(/)
print("El resultado de la divicion es:",a/b)
#5. modulo(%)
print("El resultado del modulo es:",a%b)